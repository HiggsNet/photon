import 'package:fl_clash/common/common.dart';
import 'package:fl_clash/photon/services.dart';
import 'package:fl_clash/photon/template_help.dart';
import 'package:fl_clash/widgets/widgets.dart';
import 'package:flutter/services.dart';
import 'package:flutter/widgets.dart';
import 'package:flutter_test/flutter_test.dart';

import '../helpers/test_app.dart';

void main() {
  test(
    'the help example is an importable template using generated endpoints',
    () {
      final template = Map<String, dynamic>.from(
        loadPlainYaml(photonProxyTemplateExample) as Map,
      );
      validatePhotonProxyTemplate(template);
      final preview = photonProxyTemplatePreview(template);
      expect((preview['dns'] as Map)['nameserver'], [
        'https://dns.alidns.com/dns-query',
      ]);
      expect(
        (preview['tun'] as Map)['route-exclude-address'],
        contains('192.168.0.0/16'),
      );
      final groups = (preview['proxy-groups'] as List).cast<Map>();
      expect(
        groups.map((group) => group['name']),
        containsAll([
          'My Proxy',
          'JP',
          'OpenAI',
          'Photon',
          'Photon Auto',
          'Photon Balance',
          'Photon Paths',
        ]),
      );
      expect(groups.singleWhere((group) => group['name'] == 'JP')['use'], [
        'photon-services',
      ]);
      expect(preview['rules'], contains('DOMAIN-SUFFIX,example.com,My Proxy'));
      expect(
        preview['rules'],
        contains('DOMAIN-SUFFIX,example.org,Photon Paths'),
      );
      expect(
        groups.singleWhere(
          (group) => group['name'] == 'Photon Paths',
        )['proxies'],
        ['REJECT'],
      );
      expect((preview['rules'] as List).first, 'RULE-SET,openai,OpenAI');
      expect(
        (preview['rule-providers'] as Map)['openai'],
        containsPair('behavior', 'domain'),
      );
      expect(groups.singleWhere((group) => group['name'] == 'OpenAI')['use'], [
        'photon-services',
      ]);
      expect((preview['proxy-providers'] as Map)['photon-services'], isNotNull);
    },
  );

  testWidgets('template help copies the prompt and YAML', (tester) async {
    tester.view.physicalSize = const Size(640, 900);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);
    String? copied;
    tester.binding.defaultBinaryMessenger.setMockMethodCallHandler(
      SystemChannels.platform,
      (call) async {
        if (call.method == 'Clipboard.setData') {
          copied = (call.arguments as Map)['text'] as String;
        }
        return null;
      },
    );
    addTearDown(() {
      tester.binding.defaultBinaryMessenger.setMockMethodCallHandler(
        SystemChannels.platform,
        null,
      );
    });
    await tester.pumpWidget(
      TestApp(
        locale: const Locale('en'),
        wrapInProviderScope: true,
        child: Builder(
          builder: (context) => Scaffold(
            title: 'Photon',
            body: TextButton(
              onPressed: () => showPhotonTemplateHelp(context),
              child: const Text('Help'),
            ),
          ),
        ),
      ),
    );
    await tester.tap(find.text('Help'));
    await tester.pumpAndSettle();
    expect(find.text('Kept or merged'), findsOneWidget);
    expect(find.text('Generated by Photon'), findsOneWidget);
    expect(find.text('Required routing safeguards'), findsOneWidget);
    expect(find.text('Controlled by the app'), findsOneWidget);
    final copyPrompt = find.widgetWithText(TextButton, 'Copy AI prompt');
    await tester.tap(copyPrompt);
    await tester.pumpAndSettle();
    expect(
      copied,
      tester.element(copyPrompt).appLocalizations.photonTemplateAiPrompt,
    );
    expect(copied, contains('use: [photon-services]'));
    expect(copied, contains('use Photon Paths as a rule target'));
    expect(copied, contains('Existing YAML and requested changes:'));

    final copy = find.widgetWithText(TextButton, 'Copy');
    await Scrollable.ensureVisible(tester.element(copy), alignment: 0.5);
    await tester.pumpAndSettle();
    await tester.tap(copy);
    await tester.pumpAndSettle();
    expect(copied, photonProxyTemplateExample);
    expect(find.text('Export example YAML'), findsOneWidget);
    expect(tester.takeException(), isNull);
  });
}
